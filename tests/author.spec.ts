import { test, expect } from "@playwright/test"

test("AUTHOR groups initiation and links summary sections to their tabs", async ({ page }) => {
  await page.goto("/")
  await page.getByRole("link", { name: /Open AUTHOR/i }).click()
  await expect(page.getByRole("heading", { name: "TrackWise Intake" })).toBeVisible()
  await page.getByTestId("open-demo-case-button").click()
  await expect(page.getByTestId("stage-nav-1")).toContainText("Initiation")
  await expect(page.getByTestId("stage-nav-2")).toHaveCount(0)
  await expect(page.getByTestId("stage-nav-8")).toHaveCount(0)
  await expect(page.getByTestId("stage-nav-4")).toHaveCount(0)
  await expect(page.getByTestId("stage-nav-7")).toHaveCount(0)
  await expect(page.getByTestId("stage-nav-1")).toHaveAttribute("aria-current", "step")
  await expect(page.getByTestId("footer-continue-button")).toHaveCount(0)
  await page.getByTestId("stage-nav-1").click()
  await expect(page.getByTestId("initiation-progress")).toContainText("3 of 3 complete")
  for (const stage of [1, 2, 3]) {
    await page.getByTestId(`initiation-tab-${stage}`).click()
    await expect(page.getByTestId(`initiation-tab-${stage}`)).toHaveAttribute("aria-selected", "true")
    await expect(page.getByTestId(`initiation-tab-${stage}`)).toContainText("Complete")
  }
  await page.getByTestId("case-summary-nav").click()
  await expect(page.getByTestId("case-summary-section-stage_4")).toHaveCount(0)
  await expect(page.getByTestId("case-summary-section-stage_8")).toHaveCount(0)
  await expect(page.getByTestId("case-summary-initiation-progress")).toHaveText("3 of 3 complete")
  await page.getByTestId("case-summary-section-stage_2-open-stage").click()
  await expect(page.getByTestId("initiation-tab-2")).toHaveAttribute("aria-selected", "true")
  await page.getByTestId("initiation-tab-3").click()
  await expect(page.getByTestId("footer-continue-button")).toHaveCount(0)
})
test("moving to another AUTHOR section returns the page to the top", async ({ page }) => {
  await page.goto("/author")
  await page.getByTestId("open-demo-case-button").click()
  await page.getByTestId("stage-nav-1").click()
  await page.getByTestId("initiation-tab-2").click()
  await page.evaluate(() => window.scrollTo(0, document.documentElement.scrollHeight))
  await expect.poll(() => page.evaluate(() => window.scrollY)).toBeGreaterThan(0)
  await page.getByTestId("footer-continue-button").click()
  await expect(page.getByTestId("initiation-tab-3")).toHaveAttribute("aria-selected", "true")
  await expect.poll(() => page.evaluate(() => window.scrollY)).toBe(0)
})
