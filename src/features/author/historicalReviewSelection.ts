export type HistoricalReviewCandidateRecord = {
  pr_id?: unknown
}

export type HistoricalReviewEvaluationLike = {
  record_id?: unknown
}

function normalizeHistoricalReviewRecordId(value: unknown) {
  return String(value ?? "").trim()
}

export function isHistoricalReviewCandidateRecord(
  record: HistoricalReviewCandidateRecord | null | undefined,
  currentPrId?: string | null,
) {
  const recordId = normalizeHistoricalReviewRecordId(record?.pr_id)
  if (!recordId || recordId === "-1" || recordId === "0") {
    return false
  }

  const normalizedCurrentPrId = normalizeHistoricalReviewRecordId(currentPrId)
  if (normalizedCurrentPrId && recordId === normalizedCurrentPrId) {
    return false
  }

  return true
}

export function filterHistoricalReviewCandidateRecords<T extends HistoricalReviewCandidateRecord>(
  records: T[] | null | undefined,
  currentPrId?: string | null,
) {
  return (records || []).filter((record) => isHistoricalReviewCandidateRecord(record, currentPrId))
}

export function filterHistoricalReviewRecordEvaluations<T extends HistoricalReviewEvaluationLike>(
  evaluations: T[] | null | undefined,
  validRecordIds: Iterable<string>,
) {
  const normalizedValidRecordIds = new Set(
    Array.from(validRecordIds || [])
      .map((recordId) => normalizeHistoricalReviewRecordId(recordId))
      .filter(Boolean),
  )

  if (normalizedValidRecordIds.size === 0) {
    return []
  }

  return (evaluations || []).filter((evaluation) => {
    const recordId = normalizeHistoricalReviewRecordId(evaluation?.record_id)
    return Boolean(recordId && normalizedValidRecordIds.has(recordId))
  })
}

export function buildHistoricalReviewSelectionSummary(selectedRecords: HistoricalReviewCandidateRecord[]) {
  if (selectedRecords.length === 0) {
    return null
  }

  const recordIds = selectedRecords
    .map((record) => normalizeHistoricalReviewRecordId(record.pr_id))
    .filter(Boolean)
  const preview = recordIds.slice(0, 4).join(", ")
  const remainder = recordIds.length > 4 ? `, and ${recordIds.length - 4} more` : ""

  return `Reviewed ${selectedRecords.length} saved TrackWise record${selectedRecords.length === 1 ? "" : "s"} (${preview}${remainder}).`
}

export function resolveHistoricalReviewSummary(
  summary: string | null | undefined,
  selectedRecords: HistoricalReviewCandidateRecord[],
) {
  const normalizedSummary = String(summary || "").trim()
  const selectionSummary = buildHistoricalReviewSelectionSummary(selectedRecords)
  const looksAutoGenerated = /^Reviewed \d+ saved TrackWise record(?:s)? \([^)]+\)\.$/i.test(normalizedSummary)

  if (selectionSummary) {
    if (!normalizedSummary || looksAutoGenerated) {
      return selectionSummary
    }
    return normalizedSummary
  }

  if (looksAutoGenerated) {
    return null
  }

  return normalizedSummary || null
}

export function getHistoricalReviewReviewedCount(
  selectedRecords: HistoricalReviewCandidateRecord[],
  evaluatedRecords?: unknown[] | null,
) {
  const selectedCount = Array.isArray(selectedRecords) ? selectedRecords.length : 0
  if (selectedCount > 0) {
    return selectedCount
  }
  return Array.isArray(evaluatedRecords) ? evaluatedRecords.length : 0
}
